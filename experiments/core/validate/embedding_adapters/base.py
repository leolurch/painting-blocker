from abc import ABC, abstractmethod
from collections.abc import Sequence
from typing import List

import numpy as np

EmbeddingMap = dict[str, np.ndarray]


class BaseEmbeddingModel(ABC):
    @abstractmethod
    def __init__(self):
        """Initialize the model and any necessary resources."""

    @abstractmethod
    def generate_embedding(
        self, image_path: str, pooling: Sequence[str]
    ) -> EmbeddingMap:
        """
        Generate embeddings for the image at the given path.

        Args:
            image_path: Path to the image file.
            pooling: Pooling modes to return, e.g. ["default", "avg"].

        Returns:
            A mapping of canonical pooling mode to the raw model descriptor.
            Adapters retain model-specific pooling/projection but must not apply
            cache-related casting or L2 normalization; the embedding pipeline
            owns common FP32 post-processing.
        """

    def generate_embeddings_batch(
        self, image_paths: List[str], pooling: Sequence[str]
    ) -> dict[str, np.ndarray]:
        """
        Generate embeddings for multiple images at once.

        This is the primary method for GPU-optimized batch processing.
        Subclasses should override this for efficient batched inference.

        Args:
            image_paths: List of paths to image files.
            pooling: Pooling modes to return, e.g. ["default", "avg"].

        Returns:
            A mapping of canonical pooling mode to raw descriptor arrays shaped
            ``(N, embedding_dim)``. Shared L2 normalization happens centrally.
        """
        # Default implementation: fall back to single-image processing.
        embeddings = [self.generate_embedding(path, pooling) for path in image_paths]
        if not embeddings:
            return {}
        keys = tuple(embeddings[0])
        return {key: np.stack([item[key] for item in embeddings], axis=0) for key in keys}

    @abstractmethod
    def get_model_name(self) -> str:
        """Return a unique identifier for the model."""

    @abstractmethod
    def get_dimension(self) -> int:
        """Return the dimension of the embeddings generated by this model."""

    def __del__(self):
        """Cleanup resources if needed."""
